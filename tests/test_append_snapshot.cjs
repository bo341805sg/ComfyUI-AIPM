const fs = require('fs'), vm = require('vm'), assert = require('assert');
const src = fs.readFileSync(__dirname + '/../web/aipm_ui.js', 'utf8');
const fn = src.slice(src.indexOf('function linkedAppendTimeline('), src.indexOf('function writeResultToLinkedCineTimelines('));
const box = {app:{}}; vm.createContext(box); vm.runInContext(fn, box);
const node = {outputs:[],graph:{links:{}}};
assert.equal(box.linkedAppendTimeline(node), null, 'Standalone AIPM must not need a timeline');
node.outputs = [{name:'完整结果 JSON',links:[1]}];
node.graph.links[1] = {target_id:2,target_slot:0};
const target = {type:'CineTimelinePlan',inputs:[{name:'timeline_json'}],widgets:[{name:'timeline_state',value:JSON.stringify({shots:[{shot_id:'kept',local_prompt:'edited'}]})}]};
node.graph.getNodeById = () => target;
const snapshot=box.linkedAppendTimeline(node);
assert.equal(snapshot.shots[0].local_prompt,'edited');
target.widgets[0].value='{"shots":[]}';
